"""Build results/summary.md from the raw result files. Every number quoted in the docs comes from this table.

For each case it shows the main run (results/bench.json) and a CONSERVATIVE speedup: the best time ever recorded
for the original in any run on this machine, divided by the best time ever recorded for the variant. Using the
original's best time is the least flattering choice for the speedup.
"""
import glob
import json

main = json.load(open("results/bench.json"))
best = {}  # (kind, n, variant) -> min seconds over every recorded run


def note(kind, n, variant, seconds):
    k = (kind, n, variant)
    best[k] = min(best.get(k, 1e99), min(seconds))


for path in sorted(glob.glob("results/bench*.json")):
    for c in json.load(open(path))["cases"]:
        for v, s in c["stats"].items():
            note(c["kind"], c["n"], v, s["all_s"])
for path in ("results/baseline.json", "results/baseline_unpinned_UNRELIABLE.json"):
    try:
        for c in json.load(open(path))["cases"]:
            note(c["kind"], c["n"], "original", c["all_s"])
    except FileNotFoundError:
        pass

rows = ["| Workload | Rectangles | Bins used | Original (best) | Python fixes (best) | C++ (best) | Speedup, Python fixes | Speedup, C++ | C++ speedup range across rounds of the main run | Output identical |",
        "|---|---|---|---|---|---|---|---|---|---|"]
cons = []
for c in main["cases"]:
    k, n = c["kind"], c["n"]
    o, p, v = best[(k, n, "original")], best[(k, n, "python_fixes")], best[(k, n, "native")]
    s = c["stats"]["native"]
    cons.append((k, n, o / v, o / p))
    rows.append(f"| {k} | {n:,} | {c['bins_used']} | {o:.3f} s | {p:.3f} s | {v:.4f} s | {o/p:.1f}x | {o/v:.0f}x | {s['speedup_vs_original_min']:.0f}x to {s['speedup_vs_original_max']:.0f}x | {'yes' if c['identical_output'] else 'NO'} |")

native = [x[2] for x in cons]
fixes = [x[3] for x in cons]
lines = ["# Benchmark summary (generated by tools/summarize.py)", "",
         f"Main run started {main['started']}; affinity {main['env'].get('pinned_cpus')}; {main['config']}.", "",
         "Times are the best (minimum) recorded over every run on this machine; speedups divide those best times.", ""] + rows + ["",
         f"C++ speedup: min {min(native):.1f}x, max {max(native):.0f}x over {len(native)} cases.",
         f"Pure-Python fixes speedup: min {min(fixes):.1f}x, max {max(fixes):.1f}x.",
         "All outputs identical: " + ("yes" if all(c["identical_output"] for c in main["cases"]) else "NO")]
open("results/summary.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines))
